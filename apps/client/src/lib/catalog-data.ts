// Возвращает секции каталога для выбранной категории или общий список.
export function getCatalogSections(categoryId?: number) {
  return categoryId
    ? catalogSectionsByCategory[categoryId] ?? genericCatalogSections
    : genericCatalogSections;
}

export function getCatalogCategoryId(title: string) {
  const normalizedTitle = title.trim().toLowerCase();

  for (const [categoryId, sections] of Object.entries(catalogSectionsByCategory)) {
    if (
      sections.some((section) =>
        section.items.some((item) => item.toLowerCase() === normalizedTitle),
      )
    ) {
      return Number(categoryId);
    }
  }

  return 1;
}

// Возвращает быстрые поисковые подсказки для подкатегории каталога.
export function getCatalogQuickPicks(subcategory?: string) {
  if (!subcategory) {
    return catalogQuickPicks;
  }

  return quickPicksBySubcategory[subcategory] ?? catalogQuickPicks;
}
